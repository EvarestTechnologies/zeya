"""
Score the danger-sign gate node against the evaluation corpus.

Runs ocs/nodes/danger_gate.py (or another node file) through the same sandbox the
OCS tests use, so the numbers describe what production would do.

    python -m ocs.eval.score_gate                      # the current gate
    python -m ocs.eval.score_gate --node path/to.py    # a proposed gate
    python -m ocs.eval.score_gate --report docs/eval/danger-gate-baseline.md
"""

import argparse
import sys
from collections import defaultdict
from pathlib import Path
from typing import NamedTuple

from ocs.eval.corpus import CASES, Case
from ocs.tests.sandbox import NodeHarness

DEFAULT_NODE = Path(__file__).resolve().parent.parent / "nodes" / "danger_gate.py"


class Result(NamedTuple):
    case: Case
    triggered: bool
    categories: list


def run(node_path: Path = DEFAULT_NODE) -> list[Result]:
    source = node_path.read_text()
    results = []
    for case in CASES:
        harness = NodeHarness(source)
        harness.run(case.text)
        results.append(Result(case, harness.temp_state["danger_route"] == "EMERGENCY",
                              list(harness.temp_state["danger_categories"])))
    return results


def summarise(results: list[Result]) -> dict:
    def ratio(items, pred):
        items = list(items)
        return (sum(1 for r in items if pred(r)), len(items))

    emergency = [r for r in results if r.case.label == "EMERGENCY"]
    in_scope = [r for r in emergency if r.case.category != "newborn"]
    routine = [r for r in results if r.case.label == "ROUTINE"]
    by_category = defaultdict(list)
    by_lang = defaultdict(list)
    for r in in_scope:
        by_category[r.case.category].append(r)
        by_lang[r.case.lang].append(r)
    return {
        "recall": ratio(in_scope, lambda r: r.triggered),
        "newborn_recall": ratio([r for r in emergency if r.case.category == "newborn"], lambda r: r.triggered),
        "by_category": {k: ratio(v, lambda r: r.triggered) for k, v in by_category.items()},
        "by_lang": {k: ratio(v, lambda r: r.triggered) for k, v in by_lang.items()},
        "false_alarms": ratio(routine, lambda r: r.triggered),
        "danger_questions_false_alarms": ratio([r for r in routine if r.case.kb == "7"], lambda r: r.triggered),
        "recall_by_batch": {b: ratio([r for r in in_scope if r.case.batch == b], lambda r: r.triggered)
                            for b in sorted({r.case.batch for r in in_scope})},
        "false_alarms_by_batch": {b: ratio([r for r in routine if r.case.batch == b], lambda r: r.triggered)
                                  for b in sorted({r.case.batch for r in routine})},
        "same_day_to_emergency": ratio([r for r in results if r.case.label == "SAME_DAY"], lambda r: r.triggered),
        "size": len(results),
        "misses": [r for r in emergency if not r.triggered],
        "false_alarm_cases": [r for r in routine if r.triggered],
    }


def _pct(pair) -> str:
    n, d = pair
    return f"{n}/{d} ({100 * n / d:.0f}%)" if d else "0/0"


def render(s: dict, title: str) -> str:
    lines = [f"# {title}", "",
             f"Generated by `python -m ocs.eval.score_gate`. Corpus: `ocs/tests/danger_eval_corpus.csv` ({s['size']} messages).", "",
             "| Measure | Result |", "|---|---|",
             f"| Recall, emergencies (pregnancy and after birth) | {_pct(s['recall'])} |",
             f"| Recall, newborn emergencies (outside the gate's current scope) | {_pct(s['newborn_recall'])} |",
             f"| False alarms, routine messages | {_pct(s['false_alarms'])} |",
             f"| False alarms, questions about danger signs | {_pct(s['danger_questions_false_alarms'])} |",
             f"| Same-day messages sent to the emergency path | {_pct(s['same_day_to_emergency'])} |",
             "", "## Recall by category", "", "| Category | Caught |", "|---|---|"]
    lines += [f"| {k} | {_pct(v)} |" for k, v in sorted(s["by_category"].items())]
    lines += ["", "## By batch",
              "", "v1 is the first 200 messages. v2 was added later and no pattern was tuned on it, so v2 is the fairer test of new wording.",
              "", "| Batch | Emergencies caught | Routine false alarms |", "|---|---|---|"]
    lines += [f"| {b} | {_pct(s['recall_by_batch'].get(b, (0, 0)))} | {_pct(s['false_alarms_by_batch'].get(b, (0, 0)))} |"
              for b in sorted(set(s["recall_by_batch"]) | set(s["false_alarms_by_batch"]))]
    lines += ["", "## Recall by language", "", "| Language | Caught |", "|---|---|"]
    lines += [f"| {k} | {_pct(v)} |" for k, v in sorted(s["by_lang"].items())]
    lines += ["", "## Missed emergencies", "", "| ID | Batch | Lang | Categories | Message |", "|---|---|---|---|---|"]
    lines += [f"| {r.case.id} | {r.case.batch} | {r.case.lang} | {', '.join(r.case.categories)} | {r.case.text} |" for r in s["misses"]]
    lines += ["", "## False alarms", "", "| ID | Batch | Lang | Matched | Message |", "|---|---|---|---|---|"]
    lines += [f"| {r.case.id} | {r.case.batch} | {r.case.lang} | {', '.join(r.categories)} | {r.case.text} |" for r in s["false_alarm_cases"]]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--node", type=Path, default=DEFAULT_NODE)
    parser.add_argument("--report", type=Path)
    parser.add_argument("--title", default="Danger gate score")
    args = parser.parse_args(argv)
    text = render(summarise(run(args.node)), args.title)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(text)
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
